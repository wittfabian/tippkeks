/**
 * Generates supabase/seed.sql from the vendored, public-domain openfootball
 * WM 2026 schedule (data/openfootball/*). The seed gives local dev and tests a
 * complete, realistic tournament without an external API token. In production
 * the football-data.org sync is the source of truth instead (provider
 * "football-data"); this seed uses provider "openfootball".
 *
 * Run: pnpm tsx scripts/generate-seed.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

import { germanTeamName } from "../src/lib/i18n/teamNames";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const PROVIDER = "openfootball";

type RawTeam = {
  name: string;
  fifa_code: string;
  group: string;
  flag_icon?: string;
};
type RawMatch = {
  round: string;
  date: string;
  time: string;
  team1: string;
  team2: string;
  group?: string;
  ground?: string;
};

const teams: RawTeam[] = Object.values(
  JSON.parse(readFileSync(join(root, "data/openfootball/worldcup.2026.teams.json"), "utf8")),
);
const schedule: { name: string; matches: RawMatch[] } = JSON.parse(
  readFileSync(join(root, "data/openfootball/worldcup.2026.json"), "utf8"),
);

type StageKind =
  "group" | "last_32" | "last_16" | "quarter_final" | "semi_final" | "third_place" | "final";

const STAGES: { kind: StageKind; name: string; ordinal: number }[] = [
  { kind: "group", name: "Gruppenphase", ordinal: 1 },
  { kind: "last_32", name: "Sechzehntelfinale", ordinal: 2 },
  { kind: "last_16", name: "Achtelfinale", ordinal: 3 },
  { kind: "quarter_final", name: "Viertelfinale", ordinal: 4 },
  { kind: "semi_final", name: "Halbfinale", ordinal: 5 },
  { kind: "third_place", name: "Spiel um Platz 3", ordinal: 6 },
  { kind: "final", name: "Finale", ordinal: 7 },
];

function stageKindForRound(round: string): StageKind {
  if (round.startsWith("Matchday")) return "group";
  switch (round) {
    case "Round of 32":
      return "last_32";
    case "Round of 16":
      return "last_16";
    case "Quarter-final":
      return "quarter_final";
    case "Semi-final":
      return "semi_final";
    case "Match for third place":
      return "third_place";
    case "Final":
      return "final";
    default:
      return "group";
  }
}

function matchdayForRound(round: string): number | null {
  const m = round.match(/^Matchday (\d+)$/);
  return m ? Number(m[1]) : null;
}

/** Parse "HH:MM UTC-6" + "YYYY-MM-DD" into a UTC ISO timestamp. */
function toUtcIso(date: string, time: string): string {
  const [clock, tz] = time.trim().split(/\s+/);
  const [h, min] = (clock ?? "00:00").split(":").map(Number);
  const offMatch = (tz ?? "").match(/UTC([+-]\d+)/);
  const offset = offMatch ? Number(offMatch[1]) : 0;
  const [y, mo, d] = date.split("-").map(Number);
  // UTC = local clock - offset (e.g. 13:00 at UTC-6 -> 19:00 UTC).
  return new Date(Date.UTC(y!, mo! - 1, d!, h! - offset, min ?? 0)).toISOString();
}

const teamByName = new Map(teams.map((t) => [t.name, t]));

function sql(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

const lines: string[] = [];
lines.push("-- GENERATED by scripts/generate-seed.ts — do not edit by hand.");
lines.push("-- Source: openfootball/worldcup.json (public domain). Provider: openfootball.");
lines.push("-- Local dev/test data only; production results come from the football-data.org sync.");
lines.push("");
lines.push("insert into public.sport (key, name) values ('football', 'Fußball')");
lines.push("  on conflict (key) do nothing;");
lines.push("");
lines.push(`insert into public.competition (sport_id, name, provider, external_id)`);
lines.push(
  `  select id, 'FIFA Weltmeisterschaft', ${sql(PROVIDER)}, 'world-cup' from public.sport where key = 'football'`,
);
lines.push("  on conflict (provider, external_id) do nothing;");
lines.push("");
lines.push(
  `insert into public.season (competition_id, label, starts_on, ends_on, provider, external_id)`,
);
lines.push(
  `  select id, 'WM 2026', '2026-06-11', '2026-07-19', ${sql(PROVIDER)}, 'wc-2026' from public.competition where provider = ${sql(PROVIDER)} and external_id = 'world-cup'`,
);
lines.push("  on conflict (provider, external_id) do nothing;");
lines.push("");

// Stages
for (const st of STAGES) {
  lines.push(`insert into public.stage (season_id, kind, name, ordinal)`);
  lines.push(
    `  select id, '${st.kind}', ${sql(st.name)}, ${st.ordinal} from public.season where provider = ${sql(PROVIDER)} and external_id = 'wc-2026'`,
  );
  lines.push("  on conflict (season_id, ordinal) do nothing;");
}
lines.push("");

// Teams
for (const t of teams) {
  const german = germanTeamName(t.name);
  lines.push(
    `insert into public.team (name, short_name, country_code, crest_url, provider, external_id) values (${sql(german)}, ${sql(t.fifa_code)}, ${sql(t.fifa_code)}, null, ${sql(PROVIDER)}, ${sql(t.fifa_code)}) on conflict (provider, external_id) do nothing;`,
  );
}
lines.push("");

// Fixtures
schedule.matches.forEach((m, i) => {
  const kind = stageKindForRound(m.round);
  const matchday = matchdayForRound(m.round);
  const home = teamByName.get(m.team1);
  const away = teamByName.get(m.team2);
  const extId = `wc2026-${String(i + 1).padStart(3, "0")}`;
  const kickoff = toUtcIso(m.date, m.time);
  const homeJoin = home
    ? `(select id from public.team where provider = ${sql(PROVIDER)} and external_id = ${sql(home.fifa_code)})`
    : "null";
  const awayJoin = away
    ? `(select id from public.team where provider = ${sql(PROVIDER)} and external_id = ${sql(away.fifa_code)})`
    : "null";
  lines.push(
    `insert into public.fixture (season_id, stage_id, matchday, home_team_id, away_team_id, kickoff_at, status, provider, external_id)`,
  );
  lines.push(
    `  select s.id, st.id, ${matchday ?? "null"}, ${homeJoin}, ${awayJoin}, '${kickoff}'::timestamptz, 'scheduled', ${sql(PROVIDER)}, ${sql(extId)}`,
  );
  lines.push(
    `  from public.season s join public.stage st on st.season_id = s.id and st.kind = '${kind}'`,
  );
  lines.push(`  where s.provider = ${sql(PROVIDER)} and s.external_id = 'wc-2026'`);
  lines.push(`  on conflict (provider, external_id) do nothing;`);
});
lines.push("");

writeFileSync(join(root, "supabase/seed.sql"), lines.join("\n"));
console.log(
  `Wrote supabase/seed.sql: ${teams.length} teams, ${schedule.matches.length} fixtures, ${STAGES.length} stages.`,
);
